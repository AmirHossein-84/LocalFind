#!/usr/bin/env python3
"""Synthesize the LocalFind Phase-0 evaluation corpus (P0-T003).

Generates 100 synthetic images + 20 synthetic videos with ffmpeg (no network,
no model, no private files) plus versioned corpus.json / queries.json
judgments. Fully deterministic: the same script + same ffmpeg major behavior
reproduces the same asset IDs, descriptions, and query ground truth.

Usage:
    python benchmarks/generate_corpus.py [--corpus-root <dir>]

Output layout (default <repo>/benchmarks/corpus/, git-ignored by design):
    corpus.json   validated by validate_corpus.py
    queries.json  39 judged queries (>=30 visual, exact_filename, semantic_image, negative)
    images/img_001.png ... images/img_100.png
    videos/vid_001.mp4 ... videos/vid_020.mp4

Exit codes: 0 = generated + self-validated, 1 = ffmpeg/ffprobe failure, 2 = usage error.
"""

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
GENERATOR_VERSION = "generate_corpus.py v1 (P0-T003)"
CORPUS_ID = "localfind-p0-synth-v1"
QUERY_SET_ID = "localfind-p0-synth-queries-v1"
WIDTH, HEIGHT, FPS = 320, 240, 30
LICENSE = "synthetic-CC0"
TIMEOUT_S = 180

SOLIDS = [  # (color name, hex)
    ("red", "ff0000"), ("dark-red", "8b0000"), ("green", "00c800"),
    ("blue", "0000ff"), ("yellow", "ffff00"), ("cyan", "00ffff"),
    ("magenta", "ff00ff"), ("orange", "ff8000"), ("purple", "8000ff"),
    ("lime", "80ff00"), ("teal", "008080"), ("gray", "808080"),
]

PATTERNS = [  # (name, lavfi spec template, description)
    # NOTE: lavfi option spelling is source-dependent (verified 2026-10-08 on
    # ffmpeg N-121271): bare `smptebars:...` colon form and shorthand `s=` fail
    # on some sources, so every spec below is explicit and was probe-tested.
    # {W}x{H} = frame size, {R} = fps, {S} = seconds. cellauto pins
    # random_seed=42 so generated bytes are deterministic.
    ("smptebars", "smptebars=size={W}x{H}:rate={R}:duration={S}",
     "SMPTE color bars test pattern"),
    ("smptehdbars", "smptehdbars=size={W}x{H}:rate={R}:duration={S}",
     "SMPTE horizontal HD color bars"),
    ("testsrc", "testsrc=size={W}x{H}:rate={R}:duration={S}",
     "Broadcast test pattern, moving"),
    ("testsrc2", "testsrc2=size={W}x{H}:rate={R}:duration={S}",
     "Broadcast test card with crosshair and timestamp"),
    ("rgbtestsrc", "rgbtestsrc=size={W}x{H}:rate={R}:duration={S}",
     "Red/green/blue channel test patches"),
    ("gradients", "gradients=size={W}x{H}:rate={R}:duration={S}",
     "Smooth multi-color gradient wash"),
    ("mandelbrot", "mandelbrot=size={W}x{H}:rate={R}",
     "Mandelbrot fractal still"),
    ("pal100bars", "pal100bars=size={W}x{H}:rate={R}:duration={S}",
     "PAL 100% color bars"),
]

VARIANTS = [  # (suffix, vf filter or None, note)
    ("plain", None, "unmodified"),
    ("border", "drawbox=x=0:y=0:w=iw:h=ih:c=white:t=8", "white border"),
    ("centerbox", "drawbox=x=(iw-120)/2:y=(ih-90)/2:w=120:h=90:c=white:t=fill",
     "white center box"),
    ("grid", "drawgrid=w=40:h=40:c=white@0.6:t=1", "white grid overlay"),
    ("negate", "negate", "inverted colors"),
]


def run(cmd, what):
    """Run an argv list; abort with an actionable message on failure (R-19)."""
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=TIMEOUT_S)
    except FileNotFoundError:
        sys.exit(f"ERROR: required tool not on PATH: {cmd[0]} (run scripts/doctor.ps1)")
    except subprocess.TimeoutExpired:
        sys.exit(f"ERROR: timed out after {TIMEOUT_S}s while making {what}")
    if proc.returncode != 0:
        tail = (proc.stderr or "").strip().splitlines()[-3:]
        sys.exit(f"ERROR: ffmpeg failed making {what}:\n" + "\n".join(tail))
    return proc


def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def ffprobe_duration_ms(ffprobe: str, path: Path) -> int:
    proc = run([ffprobe, "-v", "error", "-show_entries", "format=duration",
                "-of", "default=noprint_wrappers=1:nokey=1", str(path)],
               f"probe {path.name}")
    return int(round(float(proc.stdout.strip()) * 1000))


def pick_encoder(ffmpeg: str) -> str:
    proc = run([ffmpeg, "-hide_banner", "-encoders"], "encoder list")
    return "libx264" if " libx264 " in proc.stdout else "mpeg4"


def fill_spec(template: str, seconds: int) -> str:
    return template.format(W=WIDTH, H=HEIGHT, R=FPS, S=seconds)


def solid_spec(hex_: str, seconds: int) -> str:
    return f"color=c=0x{hex_}:size={WIDTH}x{HEIGHT}:rate={FPS}:duration={seconds}"


def make_image(ffmpeg: str, spec: str, vf, out: Path):
    cmd = ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
           "-f", "lavfi", "-i", spec]
    if vf:
        cmd += ["-vf", vf]
    cmd += ["-frames:v", "1", str(out)]
    run(cmd, out.name)


def make_clip(ffmpeg: str, encoder: str, spec: str, seconds: int, out: Path):
    run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
         "-f", "lavfi", "-i", spec,
         "-t", str(seconds), "-r", str(FPS), "-pix_fmt", "yuv420p",
         "-c:v", encoder, "-an", str(out)], out.name)


def make_two_tone(ffmpeg: str, encoder: str, color_a: str, color_b: str,
                  half_s: int, out: Path, tmpdir: Path):
    seg_a = tmpdir / f"{out.stem}_a.mp4"
    seg_b = tmpdir / f"{out.stem}_b.mp4"
    make_clip(ffmpeg, encoder, solid_spec(color_a, half_s), half_s, seg_a)
    make_clip(ffmpeg, encoder, solid_spec(color_b, half_s), half_s, seg_b)
    lst = tmpdir / f"{out.stem}.txt"
    lst.write_text(f"file '{seg_a.as_posix()}'\nfile '{seg_b.as_posix()}'\n", encoding="utf-8")
    run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
         "-f", "concat", "-safe", "0", "-i", str(lst), "-c", "copy", str(out)],
        out.name)


def main(argv=None):
    parser = argparse.ArgumentParser(description="Generate the synthetic P0 corpus.")
    parser.add_argument("--corpus-root", type=Path,
                        default=REPO_ROOT / "benchmarks" / "corpus")
    args = parser.parse_args(argv)
    ffmpeg = shutil.which("ffmpeg")
    ffprobe = shutil.which("ffprobe")
    if not ffmpeg or not ffprobe:
        sys.exit("ERROR: ffmpeg/ffprobe not on PATH (run scripts/doctor.ps1)")
    encoder = pick_encoder(ffmpeg)
    root = args.corpus_root
    img_dir, vid_dir = root / "images", root / "videos"
    img_dir.mkdir(parents=True, exist_ok=True)
    vid_dir.mkdir(parents=True, exist_ok=True)
    print(f"generator: {GENERATOR_VERSION} encoder={encoder}")

    assets = []
    n = 0
    # --- 100 images: 20 bases x 5 variants ---
    bases = ([("solid-" + name, solid_spec(hex_, 1), f"Solid {name} frame")
              for name, hex_ in SOLIDS]
             + [(name, fill_spec(tpl, 1), desc) for name, tpl, desc in PATTERNS])
    for base_name, spec, base_desc in bases:
        for suffix, vf, note in VARIANTS:
            n += 1
            aid = f"img_{n:03d}"
            fname = f"{aid}_{base_name}_{suffix}.png"
            make_image(ffmpeg, spec, vf, img_dir / fname)
            desc = base_desc if suffix == "plain" else f"{base_desc} ({note})"
            tags = base_name.split("-") + [suffix]
            assets.append({
                "asset_id": aid, "modality": "image", "rel_path": f"images/{fname}",
                "width": WIDTH, "height": HEIGHT, "license": LICENSE,
                "distribute": False, "provenance": f"synthetic-ffmpeg:{GENERATOR_VERSION}",
                "description": f"{desc}, {WIDTH}x{HEIGHT}.", "tags": tags,
                "sha256": sha256_of(img_dir / fname),
                "generator": {"spec": spec, "variant": suffix, "filter": vf},
            })
        print(f"images: {n}/100")
    base_of = {a["asset_id"]: a for a in assets}

    def find_img(*needles):
        for a in assets:
            if all(t in a["tags"] for t in needles):
                return a["asset_id"]
        raise AssertionError(f"no image asset matching {needles}")

    # --- 20 videos ---
    videos = []  # (aid, kind, payload, description, tags)
    tone_pairs = [("red", "ff0000", "blue", "0000ff"), ("green", "00c800", "magenta", "ff00ff"),
                  ("yellow", "ffff00", "black", "000000"), ("cyan", "00ffff", "orange", "ff8000"),
                  ("purple", "8000ff", "lime", "80ff00"), ("teal", "008080", "gray", "808080"),
                  ("white", "ffffff", "black", "000000"), ("blue", "0000ff", "yellow", "ffff00")]
    with tempfile.TemporaryDirectory() as tmp:
        tmpdir = Path(tmp)
        m = 0
        for name_a, hex_a, name_b, hex_b in tone_pairs:
            m += 1
            aid, fname = f"vid_{m:03d}", f"vid_{m:03d}_tone_{name_a}_{name_b}.mp4"
            make_two_tone(ffmpeg, encoder, hex_a, hex_b, 3, vid_dir / fname, tmpdir)
            videos.append((aid, fname, f"Two-tone clip: solid {name_a} then solid {name_b}.",
                           [name_a, name_b, "two-tone"]))
        motions = [("testsrc", 5, FPS, "Moving broadcast test pattern"),
                   ("testsrc", 5, 15, "Slow moving broadcast test pattern"),
                   ("testsrc2", 5, FPS, "Moving test card with crosshair"),
                   ("mandelbrot", 5, FPS, "Zooming fractal animation"),
                   ("cellauto", 5, FPS, "Evolving cellular-automaton pattern"),
                   ("testsrc", 8, FPS, "Long moving broadcast test pattern")]
        for src, seconds, rate, desc in motions:
            m += 1
            aid, fname = f"vid_{m:03d}", f"vid_{m:03d}_motion_{src}_{seconds}s.mp4"
            if src == "mandelbrot":
                spec = f"mandelbrot=size={WIDTH}x{HEIGHT}:rate={rate}"
            elif src == "cellauto":
                spec = (f"cellauto=size={WIDTH}x{HEIGHT}:rate={rate}:random_seed=42")
            else:
                spec = (f"{src}=size={WIDTH}x{HEIGHT}:rate={rate}:duration={seconds}")
            run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
                 "-f", "lavfi", "-i", spec,
                 "-t", str(seconds), "-r", str(FPS), "-pix_fmt", "yuv420p",
                 "-c:v", encoder, "-an", str(vid_dir / fname)], fname)
            videos.append((aid, fname, f"{desc} ({seconds}s).", ["motion", src]))
        statics = [(solid_spec(hex_, seconds), seconds, f"{label} screen ({seconds}s).",
                      [label, "static"])
                   for hex_, seconds, label in
                   [("ff0000", 1, "red"), ("808080", 2, "gray"), ("000000", 2, "black")]
                   ] + [(fill_spec("smptebars=size={W}x{H}:rate={R}:duration={S}", 1),
                         1, "Color bars (1s).", ["color-bars", "static"]),
                        (fill_spec("testsrc=size={W}x{H}:rate={R}:duration={S}", 12),
                         12, "Long test pattern (12s, segmentation material).",
                         ["test-pattern", "long"]),
                        (solid_spec("0000ff", 12),
                         12, "Long static blue screen (12s).", ["blue", "long"])]
        for spec, seconds, desc, tags in statics:
            m += 1
            aid = f"vid_{m:03d}"
            safe = desc.split(" (")[0].replace(" ", "_").replace("/", "_")
            fname = f"{aid}_{safe}.mp4"
            make_clip(ffmpeg, encoder, spec, seconds, vid_dir / fname)
            videos.append((aid, fname, desc, tags))
        print(f"videos: {m}/20")

    for aid, fname, desc, tags in videos:
        duration = ffprobe_duration_ms(ffprobe, vid_dir / fname)
        assets.append({
            "asset_id": aid, "modality": "video", "rel_path": f"videos/{fname}",
            "width": WIDTH, "height": HEIGHT, "duration_ms": duration, "fps": FPS,
            "license": LICENSE, "distribute": False,
            "provenance": f"synthetic-ffmpeg:{GENERATOR_VERSION}",
            "description": desc, "tags": tags,
            "sha256": sha256_of(vid_dir / fname),
            "generator": {"encoder": encoder, "size": [WIDTH, HEIGHT], "fps": FPS},
        })
    by_id = {a["asset_id"]: a for a in assets}
    assert len(assets) == 120, f"expected 120 assets, got {len(assets)}"

    # --- 39 judged queries ---
    queries = []
    def add(qid, text, qclass, modality, expected, notes=""):
        queries.append({"query_id": qid, "text": text, "query_class": qclass,
                        "modality": modality, "expected": expected,
                        "notes": notes, "provenance": f"synthetic:{GENERATOR_VERSION}"})

    q = 0
    for name, _ in SOLIDS:  # 12 solid-color queries
        q += 1
        needles = ["solid"] + name.split("-") + ["plain"]
        aid = find_img(*needles)
        exp = [{"asset_id": aid, "grade": 2}]
        notes = ""
        if name == "dark-red":  # difficult near-miss: plain red is partially relevant
            exp.append({"asset_id": find_img("solid", "red", "plain"), "grade": 1})
            notes = "Near-miss grading: dark-red is highly relevant, plain red partial."
        add(f"q{q:03d}", f"solid {name} image", "visual", "image", exp, notes)
    pattern_queries = [  # (query text, primary tags, secondary tags or None)
        ("color bars test pattern", ("smptebars", "plain"), ("smptehdbars", "plain")),
        ("horizontal HD color bars", ("smptehdbars", "plain"), None),
        ("broadcast test card with crosshair", ("testsrc2", "plain"), None),
        ("red green blue channel patches", ("rgbtestsrc", "plain"), None),
        ("smooth color gradient wash", ("gradients", "plain"), None),
        ("fractal pattern", ("mandelbrot", "plain"), None),
        ("PAL 100 percent color bars", ("pal100bars", "plain"), None),
        ("still broadcast test pattern", ("testsrc", "plain"), None),
    ]
    for text, primary, secondary in pattern_queries:  # 8 pattern queries
        q += 1
        exp = [{"asset_id": find_img(*primary), "grade": 2}]
        if secondary:
            exp.append({"asset_id": find_img(*secondary), "grade": 1})
        add(f"q{q:03d}", text, "visual", "image", exp)

    def vid_range(aid, frac_start, frac_end, tol=500):
        total = by_id[aid]["duration_ms"]
        return {"asset_id": aid, "grade": 2,
                "start_ms": int(total * frac_start), "end_ms": int(total * frac_end),
                "tolerance_ms": tol}

    tone_vids = [a["asset_id"] for a in assets
                 if a["modality"] == "video" and "two-tone" in a["tags"]][:4]
    tone_words = [(("red", "blue")), (("green", "magenta")), (("yellow", "black")), (("cyan", "orange"))]
    for aid, (word_a, word_b) in zip(tone_vids, tone_words):  # 8 half-clip queries
        q += 1
        add(f"q{q:03d}", f"{word_a} screen in video", "visual", "video", [vid_range(aid, 0.0, 0.5)],
            "First half of a two-tone clip.")
        q += 1
        add(f"q{q:03d}", f"{word_b} screen in video", "visual", "video", [vid_range(aid, 0.5, 1.0)],
            "Second half of a two-tone clip.")
    motion_queries = [("moving broadcast test pattern", ("motion", "testsrc")),
                      ("zooming fractal animation", ("motion", "mandelbrot"))]
    for text, tags in motion_queries:  # 2 motion queries (full-range expectations)
        q += 1
        aid = next(a["asset_id"] for a in assets
                   if a["modality"] == "video" and all(t in a["tags"] for t in tags))
        add(f"q{q:03d}", text, "visual", "video", [vid_range(aid, 0.0, 1.0)])

    add("q031", "img_014", "exact_filename", "image",
        [{"asset_id": "img_014", "grade": 2}],
        "Identifier-shaped query: must resolve without inference (R-17).")
    add("q032", "vid_003", "exact_filename", "video",
        [vid_range("vid_003", 0.0, 1.0)], "Identifier-shaped query over a video file.")
    long_blue = next(a["asset_id"] for a in assets
                     if a["modality"] == "video" and "long" in a["tags"] and "blue" in a["tags"])
    add("q033", "long static blue screen", "visual", "video", [vid_range(long_blue, 0.0, 1.0)],
        "Full 12s static clip; segmentation input for P0-T008.")
    add("q034", "warm colors", "semantic_image", "image",
        [{"asset_id": find_img("solid", c, "plain"), "grade": 1} for c in ("orange", "red", "yellow")],
        "Conceptual (non-literal): no asset is tagged 'warm'.")
    add("q035", "cool colors", "semantic_image", "image",
        [{"asset_id": find_img("solid", c, "plain"), "grade": 1} for c in ("blue", "cyan", "teal")],
        "Conceptual (non-literal): no asset is tagged 'cool'.")
    negatives = ("a black dog walking in a park", "person riding a bicycle",
                 "snowy mountain landscape", "green triangle")  # 4 negatives, q036-q039
    for k, text in enumerate(negatives, start=36):
        add(f"q{k:03d}", text, "negative", "any", [],
            "Nothing in the corpus depicts this; retriever must return nothing relevant.")
    assert len(queries) == 39, f"expected 39 queries, built {len(queries)}"

    (root / "corpus.json").write_text(json.dumps(
        {"corpus_id": CORPUS_ID, "version": 1,
         "corpus_root_note": "Locally generated synthetic media (git-ignored). "
                             "Regenerate: python benchmarks/generate_corpus.py",
         "assets": assets}, indent=2) + "\n", encoding="utf-8")
    (root / "queries.json").write_text(json.dumps(
        {"query_set_id": QUERY_SET_ID, "version": 1, "corpus_id": CORPUS_ID,
         "queries": queries}, indent=2) + "\n", encoding="utf-8")

    n_vid = sum(1 for a in assets if a["modality"] == "video")
    n_vis = sum(1 for x in queries if x["query_class"] == "visual")
    print(f"corpus: {len(assets)} assets (100 image + {n_vid} video), "
          f"{len(queries)} queries ({n_vis} visual)")
    print(f"wrote: {root / 'corpus.json'} and {root / 'queries.json'}")


if __name__ == "__main__":
    main()
